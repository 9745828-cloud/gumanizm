/** Абзацы основного текста */
export type BodyBlock =
  | { type: "p"; text: string }
  | {
      type: "quote"
      text: string
      cite?: string
      /** Ненавязчивый акцент на ключевой мысли */
      key?: boolean
    }
  | { type: "h2"; text: string }
  | { type: "list"; items: string[] }

export type ChapterSection = {
  title: string
  /** Краткий анонс (карточки, оглавление) */
  text: string
  /** Развёрнутый текст подраздела */
  body?: BodyBlock[]
}

/** Встроенная инфографика внутри раздела */
export type ChapterVisual =
  | {
      kind: "pills"
      title: string
      items: string[]
    }
  | {
      kind: "compare"
      title: string
      columns: { title: string; text: string; accent?: boolean }[]
    }
  | {
      kind: "chain"
      title: string
      steps: string[]
    }
  | {
      kind: "stats"
      title: string
      items: { value: string; label: string; sub?: string }[]
    }

/** Полнотекстовая статья внутри раздела (первая из серии — и далее) */
export type Article = {
  id: string
  title: string
  /** Краткий анонс для карточки списка */
  lead: string
  /** Тема / герой (например, «Конфуций») */
  subject?: string
  body: BodyBlock[]
}

export type Chapter = {
  id: string
  num: string
  title: string
  /** Вступление раздела — под заголовком, до подразделов */
  intro?: string
  sections: ChapterSection[]
  visual?: ChapterVisual
  /** Статьи раздела — список на странице раздела, чтение на /statya/:articleId */
  articles?: Article[]
  /**
   * Как показывать подразделы:
   * - read — сплошное чтение (по умолчанию, если есть body)
   * - cards — компактные карточки; полный текст по клику
   */
  sectionLayout?: "read" | "cards"
}

