export type ChapterSection = {
  title: string
  text: string
}

/** Встроенная инфографика внутри раздела (не отдельная страница) */
export type ChapterVisual =
  | {
      kind: "pills"
      title: string
      items: string[]
    }
  | {
      kind: "compare"
      title: string
      columns: { title: string; text: string; accent?: boolean }[]
    }
  | {
      kind: "chain"
      title: string
      steps: string[]
    }
  | {
      kind: "stats"
      title: string
      items: { value: string; label: string; sub?: string }[]
    }

